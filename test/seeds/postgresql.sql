-- @case: pg_dml_merge_shared
-- @dialects: postgresql,duckdb
-- @units: sql=;,sql=;
CREATE TABLE seed_pg_merge_target (id INT PRIMARY KEY, v TEXT NOT NULL);
-- @unit
MERGE INTO seed_pg_merge_target AS t
USING (SELECT 1 AS id, 'alpha' AS v UNION ALL SELECT 2, 'beta') AS s
ON t.id = s.id
WHEN MATCHED THEN UPDATE SET v = s.v
WHEN NOT MATCHED THEN INSERT (id, v) VALUES (s.id, s.v);

-- Query
-- @case: pg_query_distinct_on
-- @dialects: postgresql,duckdb,clickhouse
-- @units: sql=;
SELECT DISTINCT ON (team) team, score
FROM (
    SELECT 'a' AS team, 10 AS score
    UNION ALL SELECT 'a', 20
    UNION ALL SELECT 'b', 30
) AS t
ORDER BY team, score DESC;

-- Routine
-- @case: pg_routine_dollar_quote_trigger
-- @dialects: postgresql
-- @units: sql=;,sql=;,sql=;
CREATE TABLE seed_pg_docs (id INT PRIMARY KEY, body TEXT NOT NULL, touched_at TIMESTAMPTZ);
-- @unit
CREATE OR REPLACE FUNCTION seed_pg_touch_doc() RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
    NEW.touched_at := now();
    RETURN NEW;
END;
$fn$;
-- @unit
CREATE TRIGGER seed_pg_docs_touch
BEFORE INSERT OR UPDATE ON seed_pg_docs
FOR EACH ROW EXECUTE FUNCTION seed_pg_touch_doc();

