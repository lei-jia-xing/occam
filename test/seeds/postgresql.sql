-- DDL
-- @case: pg_ddl_table_identity_generated_default
-- @dialects: postgresql
-- @units: sql=;
CREATE TABLE seed_pg_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    balance NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    full_name TEXT GENERATED ALWAYS AS (email || ' name') STORED,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- @case: pg_ddl_index_include_partial
-- @dialects: postgresql
-- @units: sql=;,sql=;
CREATE TABLE seed_pg_events (
    id BIGINT PRIMARY KEY,
    user_id INT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    payload TEXT
);
-- @unit
CREATE INDEX seed_pg_events_active_idx
    ON seed_pg_events (user_id)
    INCLUDE (payload)
    WHERE active;

