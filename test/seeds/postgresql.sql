-- @case: pg_utf8_quotes_dollar_escape
-- @dialects: postgresql,duckdb
-- @units: sql=;
SELECT "Café" AS "naïve",
       'It''s fine' AS quoted,
       E'tab\there' AS escaped,
       $tag$dollar 'quoted' body$tag$ AS body,
       'héllo'::text AS casted
FROM (VALUES (1)) AS t("Café")
ORDER BY 1 NULLS LAST;

