    id INT PRIMARY KEY,
    label TEXT NOT NULL,
    hits INT NOT NULL DEFAULT 0
);
-- @unit
INSERT INTO seed_pg_upsert (id, label)
VALUES (1, 'alpha'), (2, 'beta')
ON CONFLICT (id) DO UPDATE
SET label = excluded.label, hits = seed_pg_upsert.hits + 1;

