-- Write-state application.
-- Online transitive reduction: before 'writeRelation' applies 'applyWriteState',
-- 'relationWriteDeps' emits direct edges from @sid@ to all prior
-- @relCardinalityWrites@ (for INSERT, MERGE via @relDataWrites@ superset, and
-- filtered DELETE) and to all prior @relColumnWrites@ of each written column
-- (for filtered UPDATE). Replacing those frontier sets with @Set.singleton sid@
-- therefore preserves exact transitive reachability ('backwardSlice',
-- 'closeSet', 'isValidClosure') while reducing O(N^2) write cliques to O(N)
-- chains. @relDataWrites@ is intentionally preserved untouched so direct-edge
-- queries on @ReadData@ retain every contributing write.
applyWriteState :: StatementId -> WriteKind -> [Ident] -> RelationState -> RelationState
applyWriteState sid (InsertWrite _) _ relation =
    relation
        & relDataWritesL %~ Set.insert sid
        & relCardinalityWritesL .~ Set.singleton sid
applyWriteState sid MergeWrite _ relation =
    relation
        & relDataWritesL %~ Set.insert sid
        & relCardinalityWritesL .~ Set.singleton sid
applyWriteState sid (DeleteWrite DeleteAllRows) _ relation =
    relation
        & relDataWritesL .~ Set.singleton sid
        & relCardinalityWritesL .~ Set.singleton sid
        & relColumnWritesL .~ Map.empty
applyWriteState sid (DeleteWrite DeleteFilteredRows) _ relation =
    relation
        & relDataWritesL %~ Set.insert sid
        & relCardinalityWritesL .~ Set.singleton sid
applyWriteState sid (UpdateWrite _) [] relation =
    relation & relDataWritesL %~ Set.insert sid
applyWriteState sid (UpdateWrite _) columns relation =
    relation & relColumnWritesL %~ insertColumnWrites sid columns
applyWriteState sid TruncateWrite {} _ relation =
    relation
        & relDataWritesL .~ Set.singleton sid
        & relCardinalityWritesL .~ Set.singleton sid
        & relColumnWritesL .~ Map.empty

insertColumnWrites ::
    StatementId -> [Ident] -> Map.Map Ident (Set StatementId) -> Map.Map Ident (Set StatementId)
insertColumnWrites sid columns current =
    Foldable.foldl' (\m column -> Map.insert column (Set.singleton sid) m) current columns

-- Reads

-- | Record dependency edges and touch keys generated by a 'ReadFact'.
processRead :: Eval -> ReadFact -> Eval
processRead = processReadWith resolveRelationKeys

-- | Variant of 'processRead' parameterized by custom relation-key resolution (used by views).
processReadWith :: (SessionState -> Catalog -> NameRef -> [RelationKey]) -> Eval -> ReadFact -> Eval
processReadWith resolveRelKeys eval readFact =
    let session = evalSession eval
        catalog = evalCatalog eval
        relationKeys =
            filter
                (`Map.member` catalogRelations catalog)
                (resolveRelKeys session catalog (readSource readFact))
        sequenceKeys =
            filter
                (`Map.member` catalogSequences catalog)
                (resolveSequenceKeys session catalog (readSource readFact))
        evalRelations =
            Foldable.foldl'
                ( \current key ->
                    addTouches
                        (relationTouchKeys key)
                        ( addDeps
                            (relationReadDeps session catalog key (readMode readFact) (readColumns readFact) (readOnly readFact))
                            current
                        )
                )
                eval
                relationKeys
        evalSequences =
            Foldable.foldl'
                ( \current key ->
                    addTouches
                        (sequenceTouchKeys key)
                        (addDeps (sequenceReadDeps catalog key) current)
                )
                evalRelations
                sequenceKeys
        unresolvedBarriers =
            [ ScopedBarrier
                (RelationScope reference)
                UnresolvedViewSourceBarrier
                (Just ("unresolved source of " <> nameText (nameRefName (readSource readFact))))
            | key <- relationKeys
            , Just relation <- [Map.lookup key (catalogRelations catalog)]
            , relKind relation == ViewRelation
            , reference <- Set.toList (relUnresolvedSources relation)
            , null
                [ sourceKey
                | sourceKey <- resolveViewSourceKeys session (relationKeyTemp key) catalog reference
                , Map.member sourceKey (catalogRelations catalog)
                ]
            ]
        evalBarriers = Foldable.foldl' (flip addBarrier) evalSequences unresolvedBarriers
     in if null relationKeys && null sequenceKeys
            then
                addTouch
                    (RelationBarrierKey (relationFallbackKey session (readSource readFact)))
                    evalBarriers
            else evalBarriers

-- | Dependency edges incurred when reading or incrementing a sequence.
sequenceReadDeps :: Catalog -> SequenceKey -> Set StatementId
sequenceReadDeps catalog key =
    case Map.lookup key (catalogSequences catalog) of
        Nothing -> Set.empty
        Just state ->
            Set.fromList
                ( catMaybes
                    [ sequenceDefinition state
                    , sequenceRestoredBy state
                    ]
                )
                `Set.union` sequenceWrites state

-- Trigger matching

-- | Normalized DML operation discriminant used for trigger firing lookup.
data DmlTag
    = TagInsert
    | TagUpdate ![Ident]
    | TagDelete
    | TagMerge
    | TagTruncate
    deriving (Eq, Show)

-- | Derive the 'DmlTag' corresponding to a 'WriteKind' and written column list.
dmlTagFor :: WriteKind -> [Ident] -> DmlTag
dmlTagFor kind columns =
    case kind of
        InsertWrite _ -> TagInsert
        UpdateWrite _ -> TagUpdate columns
        DeleteWrite _ -> TagDelete
        MergeWrite -> TagMerge
        TruncateWrite {} -> TagTruncate

-- | Determine whether a DML operation tag can fire a trigger event specification.
eventMatches :: DmlTag -> TriggerEvent -> Bool
eventMatches tag event =
    case (tag, event) of
        (TagInsert, TriggerInsert) -> True
        (TagUpdate columns, TriggerUpdate triggerColumns) ->
            null columns
                || null triggerColumns
                || not (Set.null (Set.intersection (Set.fromList columns) (Set.fromList triggerColumns)))
        (TagDelete, TriggerDelete) -> True
        -- A MERGE may execute INSERT, UPDATE, and DELETE actions, so it may
        -- fire any of those trigger events.
        (TagMerge, TriggerInsert) -> True
        (TagMerge, TriggerUpdate _) -> True
        (TagMerge, TriggerDelete) -> True
        (TagTruncate, TriggerTruncate) -> True
        _ -> False

-- | Return all triggers attached to @key@ that may fire on the given 'DmlTag'.
matchingTriggers :: Catalog -> RelationKey -> DmlTag -> [(TriggerKey, TriggerState)]
matchingTriggers catalog key tag =
    case lookupRelation catalog key of
        Nothing -> []
        Just relation ->
            [ (triggerKey, trigger)
            | triggerKey <- Set.toList (relTriggers relation)
            , Just trigger <- [Map.lookup triggerKey (catalogTriggers catalog)]
            , any (eventMatches tag) (triggerStateEvents trigger)
            , triggerStateTiming trigger /= TriggerInsteadOf
                || relKind relation `elem` [ViewRelation, MaterializedViewRelation]
            ]

-- | Record read dependencies, write edges, triggers, and FK constraints for a DML 'DataWrite'.
processDataWrite :: StatementId -> Eval -> DataWrite -> Eval
processDataWrite sid eval write =
    let evalReads = Foldable.foldl' processRead eval (dataWriteReads write)
        session = evalSession evalReads
        catalog = evalCatalog evalReads
        targetKeys = resolveRelationKeys session catalog (dataWriteTarget write)
        unqualified = dataWriteUnqualifiedColumns write
        writeColumns key =
            let knownColumns =
                    maybe Set.empty relColumns (lookupRelation catalog key)
                resolved
                    | Set.null knownColumns = unqualified
                    | otherwise = filter (`Set.member` knownColumns) unqualified
             in dataWriteColumns write ++ resolved
        applyTarget current key =
            let columns = writeColumns key
             in -- An unqualified assignment that names none of this target's
                -- columns belongs to a different table in a multi-table update.
                if null columns && not (null unqualified)
                    then current
                    else writeRelation sid current key (dataWriteKind write) columns (dataWriteOnly write)
     in mutateResolved applyTarget evalReads targetKeys

writeRelation :: StatementId -> Eval -> RelationKey -> WriteKind -> [Ident] -> Bool -> Eval
writeRelation sid eval key kind columns only =
    let session = evalSession eval
        catalog = evalCatalog eval
        relation = fromMaybe (newRelation TableRelation) (lookupRelation catalog key)
        tag = dmlTagFor kind columns
        matching = matchingTriggers catalog key tag
        insteadOf = [triggerKey | (triggerKey, trigger) <- matching, triggerStateTiming trigger == TriggerInsteadOf]
        isView = relKind relation `elem` [ViewRelation, MaterializedViewRelation]
        suppressOriginal = isView && not (null insteadOf)
        signature = writeSignature kind columns
        evalMarked =
            eval
                { evalVisitedWrites =
                    Set.insert (key, signature) (evalVisitedWrites eval)
                }
        evalDeps =
            addTouches
                (relationTouchKeys key)
                (addDeps (relationWriteDeps session catalog key kind columns) evalMarked)
        evalWrite =
            if suppressOriginal
                then evalDeps
                else evalDeps & evalCatalogL %~ insertRelation key (applyWriteState sid kind columns relation)
        evalTriggers =
            Foldable.foldl'
                (\current (triggerKey, _) -> expandTrigger sid current triggerKey)
                evalWrite
                matching
        evalCascades = applyForeignKeys sid evalTriggers key kind columns
        -- Fan out parent write to partition/inheritance children unless ONLY is specified.
        evalChildren =
            if only
                then evalCascades
                else
                    Foldable.foldl'
                        (writePartitionChild sid kind columns)
                        evalCascades
                        ( case kind of
                            InsertWrite _ -> partitionChildrenOf session catalog key
                            _ -> childrenOf session catalog key
                        )
     in if isView && null insteadOf
            then addViewWriteBarriers evalChildren key
            else evalChildren

writePartitionChild :: StatementId -> WriteKind -> [Ident] -> Eval -> RelationKey -> Eval
writePartitionChild sid kind columns current childKey =
    let signature = writeSignature kind columns
     in if Set.member (childKey, signature) (evalVisitedWrites current)
            then current
            else writeRelation sid current childKey kind columns False

addViewWriteBarriers :: Eval -> RelationKey -> Eval
addViewWriteBarriers eval key =
    Foldable.foldl'
        (flip addBarrier)
        eval
        [ ScopedBarrier
            (RelationScope (NameRef (relationKeyName source) (relationKeyTemp source)))
            WriteThroughViewBarrier
            (Just "write through view")
        | source <- Set.toList (transitiveSources (evalCatalog eval) key)
        ]

transitiveSources :: Catalog -> RelationKey -> Set RelationKey
transitiveSources catalog = go Set.empty
    where
        go seen current
            | Set.member current seen = Set.empty
            | Just relation <- lookupRelation catalog current =
                Set.insert current $
                    Set.unions [go (Set.insert current seen) source | source <- Set.toList (relSources relation)]
            | otherwise = Set.singleton current

-- Triggers and sequences
expandTrigger :: StatementId -> Eval -> TriggerKey -> Eval
expandTrigger sid eval triggerKey
    | Set.member triggerKey (evalVisitedTriggers eval) = eval
    | Just trigger <- Map.lookup triggerKey (catalogTriggers (evalCatalog eval)) =
        let tableKey = triggerStateTable trigger
            eval1 = eval {evalVisitedTriggers = Set.insert triggerKey (evalVisitedTriggers eval)}
            definitionDeps =
                Set.fromList (catMaybes [triggerDefinition trigger, triggerRestoredBy trigger])
            eval2 = addTouches (triggerTouchKeys triggerKey tableKey) (addDeps definitionDeps eval1)
            eval3 = Foldable.foldl' processRead eval2 (triggerStateWhenReads trigger)
         in applyTriggerBody sid eval3 (triggerStateBody trigger)
    | otherwise = eval

applyTriggerBody :: StatementId -> Eval -> TriggerBody -> Eval
applyTriggerBody sid eval = \case
    TriggerInline effects -> Foldable.foldl' (processTriggerEffect sid) eval effects
    TriggerFunction name _ ->
        addBarrier
            ( ScopedBarrier
                GlobalScope
                UnsupportedTriggerBodyBarrier
                (Just ("trigger function " <> nameText name))
            )
            eval
    TriggerOpaque ->
        addBarrier (ScopedBarrier GlobalScope OpaqueTriggerBodyBarrier Nothing) eval

processTriggerEffect :: StatementId -> Eval -> TriggerEffect -> Eval
processTriggerEffect sid eval effect =
    case effect of
        TriggerDml event -> processDmlEvent sid eval event
        TriggerRead readFact -> processRead eval readFact
        TriggerWriteSequence write -> processSequenceWrite sid eval write
        TriggerSession sessionEffect ->
            let (eval', _) = applySessionEffects sid [sessionEffect] eval
             in eval' {evalSessionTouched = True}
        TriggerBarrier scoped -> addBarrier scoped eval

processDmlEvent :: StatementId -> Eval -> DmlEvent -> Eval
processDmlEvent sid eval event =
    let session = evalSession eval
        catalog = evalCatalog eval
        (target, kind, columns) =
            case event of
                DmlInsert target' columns' ->
                    (target', InsertWrite ConflictError, columns')
                DmlUpdate target' columns' ->
                    (target', UpdateWrite UpdateFilteredRows, columns')
                DmlMerge target' columns' ->
                    (target', MergeWrite, columns')
                DmlDelete target' scope ->
                    (target', DeleteWrite scope, [])
                DmlTruncate target' behavior ->
                    (target', TruncateWrite behavior ContinueIdentity, [])
     in mutateResolved
            -- Trigger-body DML carries no `ONLY` marker: route conservatively.
            (\current key -> writeRelation sid current key kind columns False)
            eval
            (resolveRelationKeys session catalog target)

